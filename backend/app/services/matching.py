"""Matching service (plan A12): consented SMEs -> resolved facts -> eligibility + scoring -> ranked run.

DB work lives here; every decision is made by the pure engine modules in app.engine. Readiness actions
are generated by a separate call after the run is persisted and never touch ranks.
"""

from __future__ import annotations

import math
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import select, text
from sqlalchemy.orm import Session

from app.ai import cache, gateway
from app.audit import ActorLike, write_audit
from app.engine import eligibility, readiness, scoring
from app.engine.types import (
    ELIGIBLE,
    NEEDS_REVIEW,
    NOT_ELIGIBLE,
    DocumentRef,
    Fact,
    OpportunitySpec,
    SMEProfile,
)
from app.ingestion import lineage
from app.models import (
    SME,
    Document,
    Embedding,
    InfoRequest,
    MatchResult,
    MatchRun,
    Opportunity,
    ReadinessAction,
)

_SIMILARITY_SQL = text(
    """
    SELECT 1 - (a.vector <=> b.vector)
    FROM embeddings a
    JOIN embeddings b ON a.model_id = b.model_id
    WHERE a.id = :sme_embedding_id AND b.id = :opportunity_embedding_id
    """
)


# ---------------------------------------------------------------------------
# DB -> engine inputs
# ---------------------------------------------------------------------------


def opportunity_spec(opp: Opportunity) -> OpportunitySpec:
    return OpportunitySpec(
        id=opp.id,
        closing_date=opp.closing_date,
        contract_start=opp.contract_start,
        mandatory_criteria=list(opp.mandatory_criteria or []),
        preferred_criteria=list(opp.preferred_criteria or []),
        weights=dict(opp.weights or {}),
        capability_text=opp.capability_text,
    )


def build_profile(session: Session, sme: SME) -> SMEProfile:
    """Resolved facts (lineage.resolve) and active (non-superseded) documents for one SME."""
    docs = list(
        session.scalars(
            select(Document)
            .where(Document.sme_id == sme.id, Document.superseded_by_document_id.is_(None))
            .order_by(Document.id)
        )
    )
    all_doc_types = dict(
        session.execute(select(Document.id, Document.doc_type).where(Document.sme_id == sme.id))
        .tuples()
        .all()
    )
    facts = {
        key: Fact.from_resolution(key, resolution, all_doc_types)
        for key, resolution in lineage.resolve_profile(session, sme.id).items()
    }
    return SMEProfile(
        sme_id=sme.id,
        facts=facts,
        lat=sme.lat,
        lon=sme.lon,
        documents=[DocumentRef(d.id, d.filename, d.doc_type, d.issue_date, d.period_end) for d in docs],
    )


def _sme_embedding(
    session: Session, sme: SME, description: str, model_id: str, mode: str
) -> Embedding | None:
    """Embedding of the SME's current services text with the opportunity's model (reuse or create)."""
    sha = cache.sha256_hex(description.encode("utf-8"))
    row = session.scalars(
        select(Embedding).where(
            Embedding.owner_type == "sme",
            Embedding.owner_id == sme.id,
            Embedding.model_id == model_id,
            Embedding.text_sha256 == sha,
        )
    ).first()
    if row is not None:
        return row
    try:
        row = gateway.embed_and_store(session, "sme", sme.id, description, mode=mode)
    except (gateway.CacheMiss, gateway.LiveUnavailable):
        return None
    return row if row.model_id == model_id else None


def similarity(session: Session, sme_embedding: Embedding, opp_embedding: Embedding) -> float | None:
    """Cosine similarity computed in Postgres with pgvector; NaN (all-zero vector) becomes 0.0."""
    value = session.execute(
        _SIMILARITY_SQL,
        {
            "sme_embedding_id": sme_embedding.id,
            "opportunity_embedding_id": opp_embedding.id,
        },
    ).scalar()
    if value is None:
        return None
    value = float(value)
    return 0.0 if math.isnan(value) else value


def _open_request(session: Session, opportunity_id: int, sme_id: int) -> bool:
    return (
        session.scalars(
            select(InfoRequest.id)
            .where(
                InfoRequest.opportunity_id == opportunity_id,
                InfoRequest.sme_id == sme_id,
                InfoRequest.status == "open",
            )
            .limit(1)
        ).first()
        is not None
    )


