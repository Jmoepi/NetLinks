# Run
# ---------------------------------------------------------------------------


def run_match(session: Session, opportunity_id: int, actor: ActorLike, mode: str | None = None) -> MatchRun:
    """Evaluate every consented SME against the opportunity and persist a ranked run. Flushes, never commits.

    Raises LookupError for an unknown opportunity; gateway.CacheMiss / LiveUnavailable when the
    opportunity's capability text cannot be embedded in the current AI mode.
    """
    opp = session.get(Opportunity, opportunity_id)
    if opp is None:
        raise LookupError(f"Opportunity {opportunity_id} not found")
    spec = opportunity_spec(opp)
    scoring.validate_weights(spec.weights)
    mode = mode or gateway.get_mode(session)

    opp_embedding = gateway.embed_and_store(
        session, "opportunity", opp.id, opp.capability_text or "", mode=mode
    )
    smes = list(session.scalars(select(SME).order_by(SME.id)))
    consented = [s for s in smes if s.consent_status == "granted"]
    excluded = len(smes) - len(consented)

    evaluated: list[dict[str, Any]] = []
    for sme in consented:
        profile = build_profile(session, sme)
        elig = eligibility.evaluate(profile, spec)
        description = profile.fact("services_description")
        sim = None
        if description.status in ("ok", "low_confidence") and description.value:
            emb = _sme_embedding(session, sme, str(description.value), opp_embedding.model_id, mode)
            sim = similarity(session, emb, opp_embedding) if emb is not None else None
        fit = scoring.score(profile, spec, sim, opp_embedding.model_id)
        evaluated.append({"sme": sme, "eligibility": elig, "score": fit})

    eligible = sorted(
        (e for e in evaluated if e["eligibility"].status == ELIGIBLE),
        key=lambda e: (-e["score"].total, e["sme"].name),
    )
    ranks = {e["sme"].id: i for i, e in enumerate(eligible, start=1)}
    counts = {
        ELIGIBLE: sum(e["eligibility"].status == ELIGIBLE for e in evaluated),
        NEEDS_REVIEW: sum(e["eligibility"].status == NEEDS_REVIEW for e in evaluated),
        NOT_ELIGIBLE: sum(e["eligibility"].status == NOT_ELIGIBLE for e in evaluated),
        "considered": len(evaluated),
        "excluded_no_consent": excluded,
    }

    run = MatchRun(opportunity_id=opp.id, run_by_role=actor.role, ai_mode=mode, counts=counts)
    session.add(run)
    session.flush()
    for e in evaluated:
        sme = e["sme"]
        session.add(
            MatchResult(
                run_id=run.id,
                sme_id=sme.id,
                status=e["eligibility"].status,
                checks=[c.to_dict() for c in e["eligibility"].checks],
                score_total=e["score"].total,
                components=[c.to_dict() for c in e["score"].components],
                rank=ranks.get(sme.id),
                awaiting_sme=_open_request(session, opp.id, sme.id),
            )
        )
    session.flush()
    write_audit(
        session,
        actor,
        "match_run",
        "match_run",
        run.id,
        {
            "opportunity_id": opp.id,
            "ai_mode": mode,
            "counts": counts,
            "embedding_model_id": opp_embedding.model_id,
            "weights": spec.weights,
            "ranking": [
                {"sme_id": e["sme"].id, "rank": ranks[e["sme"].id], "score": e["score"].total}
                for e in eligible
            ],
        },
    )
    return run


def run_results(session: Session, run_id: int) -> list[MatchResult]:
    return list(
        session.scalars(select(MatchResult).where(MatchResult.run_id == run_id).order_by(MatchResult.id))
    )


def latest_run(session: Session, opportunity_id: int) -> MatchRun | None:
    return session.scalars(
        select(MatchRun)
        .where(MatchRun.opportunity_id == opportunity_id)
        .order_by(MatchRun.id.desc())
        .limit(1)
    ).first()


# ---------------------------------------------------------------------------
# Readiness (separate call; never touches ranks)
# ---------------------------------------------------------------------------


def generate_readiness(session: Session, run: MatchRun) -> list[ReadinessAction]:
    """Persist readiness actions for a run from its stored checks and components (replaces earlier ones)."""
    opp = session.get(Opportunity, run.opportunity_id)
    spec = opportunity_spec(opp)
    results = [
        {"sme_id": r.sme_id, "checks": r.checks, "components": r.components}
        for r in run_results(session, run.id)
    ]
    session.query(ReadinessAction).filter(ReadinessAction.run_id == run.id).delete()
    rows = [
        ReadinessAction(
            sme_id=a["sme_id"],
            opportunity_id=run.opportunity_id,
            run_id=run.id,
            category=a["category"],
            text=a["text"],
        )
        for a in readiness.generate(results, spec)
    ]
    session.add_all(rows)
    session.flush()
    return rows


# ---------------------------------------------------------------------------
# Info requests: awaiting flag
# ---------------------------------------------------------------------------


def refresh_awaiting(session: Session, opportunity_id: int, sme_id: int) -> None:
    """Set awaiting_sme on the SME's result in the latest run from the open-request state."""
    run = latest_run(session, opportunity_id)
    if run is None:
        return
    awaiting = _open_request(session, opportunity_id, sme_id)
    for result in session.scalars(
        select(MatchResult).where(MatchResult.run_id == run.id, MatchResult.sme_id == sme_id)
    ):
        result.awaiting_sme = awaiting
    session.flush()


def mark_requests_responded(session: Session, sme_id: int, actor: ActorLike) -> list[InfoRequest]:
    """Called when an SME uploads a document: their open info requests become responded."""
    open_requests = list(
        session.scalars(
            select(InfoRequest)
            .where(InfoRequest.sme_id == sme_id, InfoRequest.status == "open")
            .order_by(InfoRequest.id)
        )
    )
    now = datetime.now(UTC)
    for req in open_requests:
        req.status = "responded"
        req.responded_at = now
        write_audit(
            session,
            actor,
            "info_request_responded",
            "info_request",
            req.id,
            {"opportunity_id": req.opportunity_id, "sme_id": sme_id, "kind": req.kind},
        )
    session.flush()
    for opportunity_id in {r.opportunity_id for r in open_requests}:
        refresh_awaiting(session, opportunity_id, sme_id)
    return open_requests
